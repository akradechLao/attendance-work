"use client";

import { useState, useEffect } from "react";

const mottos = [
  "วันใหม่ โอกาสใหม่ ทุกก้าวคือความสำเร็จ",
  "เริ่มต้นเช้านี้ด้วยรอยยิ้มและความมุ่งมั่น",
  "ทุกวันคือโอกาสที่จะเป็นเวอร์ชันที่ดีกว่าของตัวเอง",
  "ทำงานด้วยใจ สำเร็จด้วยความตั้งใจ",
  "เช้านี้คือของขวัญ ทำงานให้เต็มที่กันเถอะ",
  "ทุกความพยายามไม่เคยทรยศ ลุยเลย!",
  "เริ่มเช้า ทำดี มีชัยไปกว่าครึ่ง",
  "พลังบวกเริ่มจากตัวเรา ขอให้วันนี้เป็นวันที่ดี",
  "ทำงานที่รัก รักในสิ่งที่ทำ สำเร็จอยู่ไม่ไกล",
  "ทุกปัญหาคือบทเรียน ทุกวันคือการเติบโต",
  "วันนี้จะเป็นวันที่ยอดเยี่ยม แค่เริ่มลงมือทำ",
  "ความสำเร็จเริ่มจากก้าวเล็กๆ วันนี้ก้าวแรกเริ่มแล้ว",
  "สู้ๆ วันนี้ต้องดีกว่าเมื่อวานแน่นอน",
  "เช้าที่สดใส เริ่มต้นทำงานด้วยพลังเต็มเปี่ยม",
  "ทุกงานที่ทำคือการสร้างคุณค่า ขอให้ภูมิใจในตัวเอง",
];

export default function MottoBanner() {
  const [motto, setMotto] = useState("");

  useEffect(() => {
    const idx = Math.floor(Math.random() * mottos.length);
    setMotto(mottos[idx]);
  }, []);

  if (!motto) return null;

  return (
    <div className="rounded-xl gradient-gold p-4 text-white text-center font-medium text-sm shadow-gold mb-6">
      {motto}
    </div>
  );
}
